
<?php

session_start();

require_once __DIR__ . '/vendor/autoload.php';

use Napstar\MultilingualTranslationSystem\Controllers\AuthController;
use Napstar\MultilingualTranslationSystem\Services\TwoFactorAuth;

if (!isset($_SESSION['user_id'])) {
    header('Location: login.php');
    exit;
}

$auth = new AuthController();
$twoFactor = new TwoFactorAuth();

$userId = (int) $_SESSION['user_id'];
$settings = $auth->getTwoFactorSettings($userId);

$error = null;
$success = null;

if (
    $_SERVER['REQUEST_METHOD'] === 'POST'
    && isset($_POST['enable_2fa'])
) {
    $secret = $_SESSION['two_factor_setup_secret'] ?? '';
    $code = trim($_POST['code'] ?? '');

    if ($secret === '') {
        $error = 'Your setup session expired. Please reload the page.';
    } elseif (!$twoFactor->verifyCode($secret, $code)) {
        $error = 'Invalid code. Check your authenticator app and try again.';
    } else {
        if ($auth->updateTwoFactorSettings($userId, $secret, true)) {
            unset($_SESSION['two_factor_setup_secret']);
            $success = 'Two-factor authentication has been enabled.';
            $settings = $auth->getTwoFactorSettings($userId);
        } else {
            $error = 'Unable to save your settings. Please try again.';
        }
    }
}

if (
    empty($_SESSION['two_factor_setup_secret'])
    && (
        $settings === null
        || (int) $settings['two_factor_enabled'] !== 1
    )
) {
    $_SESSION['two_factor_setup_secret'] =
        $twoFactor->generateSecret();
}

$secret = $_SESSION['two_factor_setup_secret'] ?? null;

$otpUrl = $secret !== null
    ? $twoFactor->getOtpAuthUrl(
        'Multilingual Translation System',
        $_SESSION['user_email'],
        $secret
    )
    : null;

?>

<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>Set Up Two-Factor Authentication</title>
    <link rel="stylesheet" href="public/css/app.css">
    <style>
.back-dashboard {
    margin-top: 24px;
    text-align: center;
}

.dashboard-button {
    display: inline-flex;
    align-items: center;
    justify-content: center;
    gap: 8px;
    padding: 12px 20px;
    background: #2563eb;
    color: #ffffff;
    text-decoration: none;
    border-radius: 8px;
    font-weight: 600;
    transition: background 0.2s ease;
}

.dashboard-button:hover {
    background: #1d4ed8;
    color: #ffffff;
}
</style>
</head>
<body>
<main class="two-factor-page">

<div class="back-dashboard">
    <a href="dashboard.php" class="dashboard-button">
        <i class="fas fa-arrow-left"></i>
        Back to Dashboard
    </a>
</div>
    <section class="two-factor-card">
        <div class="two-factor-icon" aria-hidden="true">🔐</div>

    <?php if ($error !== null): ?>
        <p class="error">
            <?= htmlspecialchars($error, ENT_QUOTES, 'UTF-8') ?>
        </p>
    <?php endif; ?>

    <?php if ($success !== null): ?>
        <p class="success">
            <?= htmlspecialchars($success, ENT_QUOTES, 'UTF-8') ?>
        </p>
    <?php endif; ?>

    <?php if ($settings !== null && (int) $settings['two_factor_enabled'] === 1): ?>

        <p>Two-factor authentication is enabled for your account.</p>

    <?php elseif ($secret !== null): ?>

        <p>1. Open Google Authenticator, Microsoft Authenticator, or another TOTP-compatible app.</p>

        <p>2. Add a new account and enter this secret key:</p>

        <p>
            <strong>
                <?= htmlspecialchars($secret, ENT_QUOTES, 'UTF-8') ?>
            </strong>
        </p>

        <p>3. Enter the six-digit code generated by the app to confirm setup.</p>

        <form method="POST" action="two-factor-setup.php">
            <label for="code">Authenticator code</label>

            <input
                type="text"
                id="code"
                name="code"
                inputmode="numeric"
                pattern="[0-9]{6}"
                maxlength="6"
                autocomplete="one-time-code"
                required
            >

            <button type="submit" name="enable_2fa" value="1">
                Enable Two-Factor Authentication
            </button>
        </form>

        <p>
            <a href="dashboard.php">Return to dashboard</a>
        </p>

    <?php endif; ?>
    </section>
</main>
</body>
</html>
